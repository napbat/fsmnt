    #[test]
    fn poly1305_eval_rfc8439_with_s_zero() {
        // RFC 8439 §2.5.2 R (the first half of the example key).
        let r: [u8; 16] = [
            0x85, 0xd6, 0xbe, 0x78, 0x57, 0x55, 0x6d, 0x33, 0x7f, 0x44, 0x52, 0xfe, 0x42, 0xd5,
            0x06, 0xa8,
        ];

        // RFC 8439 §2.5.2 message (34 bytes). The RFC tag with the full
        // key (R || S) is a8061dc1305136c6c22b8baf0c0127a9. With S zeroed
        // (kernel `poly1305_core_emit(nonce = NULL)`) the expected tag is
        // a7039d36354384c8776c94ffcab7318d.
        //
        // `poly1305_eval` requires 16-byte-aligned input in production (the
        // caller always supplies NH-hash output). This test uses the
        // underlying `poly1305_with_zero_s` helper directly with
        // `compute_unpadded`, which is what `poly1305_eval` delegates to.
        // For full-block-only inputs the two paths are identical; the RFC
        // example exercises the partial-block path purely for arithmetic
        // cross-checking.
        let msg = b"Cryptographic Forum Research Group";
        let mac = poly1305_with_zero_s(&r);
        let tag = mac.compute_unpadded(msg);
        let mut out = [0u8; 16];
        out.copy_from_slice(tag.as_slice());

        let expected: [u8; 16] = [
            0xa7, 0x03, 0x9d, 0x36, 0x35, 0x43, 0x84, 0xc8, 0x77, 0x6c, 0x94, 0xff, 0xca, 0xb7,
            0x31, 0x8d,
        ];
        assert_eq!(out, expected);
    }

    #[test]
    fn adiantum_wrong_key_smoke() {
        // Use the same vector as `adiantum_decrypt_kat_short` but with a
        // bit-flipped key. Adiantum is unauthenticated: decryption MUST
        // return Ok, preserve length, but produce bytes different from
        // the true plaintext.
        //
        // KEY[0]: 0x9e ^ 1 = 0x9f. All other bytes unchanged.
        #[rustfmt::skip]
        const KEY: [u8; ADIANTUM_KEY_SIZE] = [
            0x9f, 0xeb, 0xb2, 0x49, 0x3c, 0x1c, 0xf5, 0xf4, 0x6a, 0x99, 0xc2, 0xc4, 0xdf, 0xb1, 0xf4, 0xdd,
            0x75, 0x20, 0x57, 0xea, 0x2c, 0x4f, 0xcd, 0xb2, 0xa5, 0x3d, 0x7b, 0x49, 0x1e, 0xab, 0xfd, 0x0f,
        ];
        #[rustfmt::skip]
        const IV: [u8; ADIANTUM_TWEAK_SIZE] = [
            0xdf, 0x63, 0xd4, 0xab, 0xd2, 0x49, 0xf3, 0xd8, 0x33, 0x81, 0x37, 0x60, 0x7d, 0xfa, 0x73, 0x08,
            0xd8, 0x49, 0x6d, 0x80, 0xe8, 0x2f, 0x62, 0x54, 0xeb, 0x0e, 0xa9, 0x39, 0x5b, 0x45, 0x7f, 0x8a,
        ];
        #[rustfmt::skip]
        const PT: &[u8] = &[
            0x67, 0xc9, 0xf2, 0x30, 0x84, 0x41, 0x8e, 0x43, 0xfb, 0xf3, 0xb3, 0x3e, 0x79, 0x36, 0x7f, 0xe8,
        ];
        #[rustfmt::skip]
        const CT: &[u8] = &[
            0x6d, 0x32, 0x86, 0x18, 0x67, 0x86, 0x0f, 0x3f, 0x96, 0x7c, 0x9d, 0x28, 0x0d, 0x53, 0xec, 0x9f,
        ];

        let cipher = AdiantumCipher::new(&KEY);
        let mut buf = CT.to_vec();
        cipher
            .decrypt_in_place(&IV, &mut buf)
            .expect("wrong-key decrypt still returns Ok");
        assert_eq!(buf.len(), PT.len(), "Adiantum is length-preserving");
        assert_ne!(buf, PT, "wrong key MUST NOT recover plaintext");
    }
