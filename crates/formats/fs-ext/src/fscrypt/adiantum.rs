//! Adiantum (`adiantum(xchacha12, aes)` with `nhpoly1305`) read-only
//! decryption for fscrypt v2 policies.
//!
//! Construction reference: Linux `crypto/adiantum.c` and
//! `crypto/nhpoly1305.c`. Paper: Crowley & Biggers, IACR ePrint
//! 2018/720 ("Adiantum: length-preserving encryption for entry-level
//! processors").
//!
//! This module is private to the `fscrypt` parent module: callers use
//! [`AdiantumCipher::new`] + [`AdiantumCipher::decrypt_in_place`]. All
//! NH / Poly1305 wrapping and subkey types stay private.

#![cfg(feature = "fscrypt")]

use zeroize::{Zeroize, ZeroizeOnDrop};

use crate::error::{ExtError, Result};

// === Constants ===========================================================

/// 32-byte Adiantum master key (used directly as XChaCha12 stream key K_S).
pub(crate) const ADIANTUM_KEY_SIZE: usize = 32;

/// 32-byte Adiantum tweak (`.ivsize` of kernel `adiantum(xchacha12,aes)`).
pub(crate) const ADIANTUM_TWEAK_SIZE: usize = 32;

/// AES-256 inner block cipher key length.
const AES_KEY_SIZE: usize = 32;

/// Poly1305 `R` key length (we always pair it with 16 zero bytes for
/// the `S` half to model kernel `poly1305_core_emit(nonce = NULL)`).
const POLY1305_R_SIZE: usize = 16;

/// NH hash key length, per kernel `crypto/nhpoly1305.c`. Note this is
/// the key size, not the chunk size (NH_MESSAGE_UNIT * NH_NUM_STRIDES =
/// 1024 bytes is the chunk size).
const NH_KEY_SIZE: usize = 1072;

/// Total subkey material derived from one XChaCha12 keystream run on
/// the 32-byte master key with a fixed IV.
const SUBKEY_BYTES: usize = AES_KEY_SIZE + POLY1305_R_SIZE + POLY1305_R_SIZE + NH_KEY_SIZE;
// 32 + 16 + 16 + 1072 == 1136

// === Subkey schedule =====================================================

/// Cached subkeys derived once per [`AdiantumCipher`] instance via
/// XChaCha12. Order matches kernel `adiantum_setkey` (see §4.3 of the
/// design doc).
#[derive(Zeroize, ZeroizeOnDrop)]
struct Subkeys {
    aes: [u8; AES_KEY_SIZE],
    header_poly: [u8; POLY1305_R_SIZE],
    msg_poly: [u8; POLY1305_R_SIZE],
    nh: [u8; NH_KEY_SIZE],
}

impl Subkeys {
    fn derive(stream_key: &[u8; ADIANTUM_KEY_SIZE]) -> Self {
        use chacha20::XChaCha12;
        use chacha20::cipher::{KeyIvInit, StreamCipher};

        // Kernel adiantum_setkey IV: data->iv[0] = cpu_to_le32(1); rest zero.
        // RustCrypto XChaCha nonce is 24 bytes; counter starts at 0.
        let mut nonce = [0u8; 24];
        nonce[0..4].copy_from_slice(&1u32.to_le_bytes());

        let mut stream = XChaCha12::new(stream_key.into(), (&nonce).into());

        let mut buf = [0u8; SUBKEY_BYTES];
        stream.apply_keystream(&mut buf);

        let mut aes = [0u8; AES_KEY_SIZE];
        let mut header_poly = [0u8; POLY1305_R_SIZE];
        let mut msg_poly = [0u8; POLY1305_R_SIZE];
        let mut nh = [0u8; NH_KEY_SIZE];

        // Order: K_E (32) || K_HEADER_POLY (16) || K_MSG_POLY (16) || K_NH (1072)
        let (a, rest) = buf.split_at(AES_KEY_SIZE);
        aes.copy_from_slice(a);
        let (h, rest) = rest.split_at(POLY1305_R_SIZE);
        header_poly.copy_from_slice(h);
        let (m, n) = rest.split_at(POLY1305_R_SIZE);
        msg_poly.copy_from_slice(m);
        nh.copy_from_slice(n);

        // Scrub the keystream scratch buffer — it contained derived key
        // material in plaintext.
        buf.zeroize();

        Self {
            aes,
            header_poly,
            msg_poly,
            nh,
        }
    }
}

// === Public API ==========================================================

/// One Adiantum cipher instance, bound to a single 32-byte master key.
/// Subkeys are derived eagerly and cached for reuse across many
/// `decrypt_in_place` calls (typical for content blocks within one
/// open file, or directory entries within one open directory).
#[derive(Zeroize, ZeroizeOnDrop)]
pub(crate) struct AdiantumCipher {
    /// XChaCha12 stream key K_S. Stored separately from the subkey
    /// schedule because the stream phase of `decrypt_in_place` needs
    /// it directly.
    stream_key: [u8; ADIANTUM_KEY_SIZE],
    subkeys: Subkeys,
}

impl AdiantumCipher {
    /// Build a cipher instance from a 32-byte master key.
    ///
    /// The 1136-byte subkey schedule is derived once here; subsequent
    /// `decrypt_in_place` calls reuse it.
    pub(crate) fn new(key: &[u8; ADIANTUM_KEY_SIZE]) -> Self {
        let subkeys = Subkeys::derive(key);
        Self {
            stream_key: *key,
            subkeys,
        }
    }

    /// Decrypt one Adiantum ciphertext block in place. `buf` must be at
    /// least 16 bytes — fscrypt enforces this (filename padding ≥ 16,
    /// content blocks always 4096), but we re-check fail-closed.
    ///
    /// Adiantum decrypt (paper §4, kernel `adiantum.c`). Splitting
    /// `C = C_L || C_R` with `|C_R| = 16`, the output `P_L || P_R`
    /// is computed as:
    ///
    /// 1. `C_M = C_R + H(T, C_L)` mod 2^128
    /// 2. `P_L = C_L ⊕ S(K_S, C_M)` (XChaCha12 stream over `buf[..n-16]`)
    /// 3. `P_M = AES_256^{-1}(K_E, C_M)`
    /// 4. `P_R = P_M − H(T, P_L)` mod 2^128
    pub(crate) fn decrypt_in_place(
        &self,
        tweak: &[u8; ADIANTUM_TWEAK_SIZE],
        buf: &mut [u8],
    ) -> Result<()> {
        use chacha20::XChaCha12;
        use chacha20::cipher::{KeyIvInit, StreamCipher};

        if buf.len() < 16 {
            return Err(ExtError::InvalidFscryptPolicy {
                inode: 0,
                reason: "Adiantum ciphertext < 16 bytes",
            });
        }

        let n = buf.len();
        // m_l_bits is the bit-length of C_L (= P_L), which is (n - 16) bytes.
        let m_l_bits: u64 = ((n - 16) as u64).wrapping_mul(8);

        // Step 1: C_M = C_R + H(T, C_L) mod 2^128
        // Read C_R (the tail 16 bytes) before the stream cipher touches C_L.
        let c_r_bytes: [u8; 16] = buf[n - 16..].try_into().expect("16-byte tail");
        let h_cl = hash_h(
            &self.subkeys.header_poly,
            &self.subkeys.msg_poly,
            &self.subkeys.nh,
            tweak,
            m_l_bits,
            &buf[..n - 16],
        );
        let c_m_u128 = u128::from_le_bytes(c_r_bytes).wrapping_add(u128::from_le_bytes(h_cl));
        let c_m = c_m_u128.to_le_bytes();

        // Step 2: P_L = C_L ⊕ S(K_S, C_M) — XChaCha12 stream over buf[..n-16].
        let nonce = stream_iv(&c_m);
        let mut stream = XChaCha12::new((&self.stream_key).into(), (&nonce).into());
        stream.apply_keystream(&mut buf[..n - 16]);
        // buf[..n-16] now holds P_L.

        // Step 3: P_M = AES_256^{-1}(K_E, C_M)
        let p_m = aes256_decrypt_block(&self.subkeys.aes, &c_m);

        // Step 4: P_R = P_M − H(T, P_L) mod 2^128
        // This second hash runs over buf[..n-16] which is now P_L (after step 2).
        let h_pl = hash_h(
            &self.subkeys.header_poly,
            &self.subkeys.msg_poly,
            &self.subkeys.nh,
            tweak,
            m_l_bits,
            &buf[..n - 16],
        );
        let p_r_u128 = u128::from_le_bytes(p_m).wrapping_sub(u128::from_le_bytes(h_pl));
        buf[n - 16..].copy_from_slice(&p_r_u128.to_le_bytes());

        Ok(())
    }
}

// === NH hash =============================================================
//
// NH from kernel `crypto/nhpoly1305.c`. Processes a single chunk
// (up to 1024 bytes; final chunk zero-padded to 16-byte boundary)
// and outputs 32 bytes (four u64 lanes, little-endian).
//
// Direct Rust port of kernel `nh_generic`. Per 16-byte message unit
// (words m0..m3), the key pointer advances by 4 u32 words (= 16 bytes).
// Each unit reads a 16-word window from the (post-advance) base; the
// four passes occupy successive 4-word strides within that window:
//   pass 0: key[0..3], pass 1: key[4..7], pass 2: key[8..11], pass 3: key[12..15]
// Each pass accumulates: (m0+k[0])*(m2+k[2]) + (m1+k[1])*(m3+k[3]).
// Total key consumed across a 1024-byte chunk: 64 units * 4 word advance
// + 12 trailing words = 268 u32 words = 1072 bytes = NH_KEY_SIZE.

const NH_MESSAGE_UNIT: usize = 16;
const NH_NUM_PASSES: usize = 4;
const NH_CHUNK_BYTES: usize = 1024;

fn le_u32_at(buf: &[u8], offset: usize) -> u32 {
    u32::from_le_bytes(buf[offset..offset + 4].try_into().expect("4-byte slice"))
}

fn nh_chunk(key: &[u8; NH_KEY_SIZE], msg: &[u8]) -> [u8; 32] {
    debug_assert!(msg.len() <= NH_CHUNK_BYTES, "NH chunk exceeds 1024 bytes");

    let full_units = msg.len() / NH_MESSAGE_UNIT;
    let tail_len = msg.len() % NH_MESSAGE_UNIT;

    let mut sums = [0u64; NH_NUM_PASSES];

    // Process full 16-byte units directly from `msg` — no copy needed.
    //
    // Matches kernel `nh_generic`: per message unit, the key pointer
    // advances by NH_MESSAGE_UNIT / sizeof(u32) = 4 u32 words (16 bytes).
    // Within each unit's 16-word window, pass p reads at base + p*4:
    //   sums[0] uses key[0..3], sums[1] key[4..7], sums[2] key[8..11],
    //   sums[3] key[12..15].
    // Total key consumed per unit: 16 u32 words (but pointer only advances
    // 4), so for unit i the window starts at word i*4 (byte i*16).
    for unit in 0..full_units {
        let msg_base = unit * NH_MESSAGE_UNIT;
        let m0 = le_u32_at(msg, msg_base);
        let m1 = le_u32_at(msg, msg_base + 4);
        let m2 = le_u32_at(msg, msg_base + 8);
        let m3 = le_u32_at(msg, msg_base + 12);

        // Key pointer base in bytes: unit * 4 u32 words * 4 bytes = unit * 16.
        let key_ptr = unit * NH_MESSAGE_UNIT;

        for (pass, sum) in sums.iter_mut().enumerate() {
            // pass p offsets 4*p u32 words = p*16 bytes from key_ptr.
            let k_base = key_ptr + pass * NH_MESSAGE_UNIT;
            let k0 = le_u32_at(key, k_base);
            let k1 = le_u32_at(key, k_base + 4);
            let k2 = le_u32_at(key, k_base + 8);
            let k3 = le_u32_at(key, k_base + 12);

            // Kernel: sums[p] += (m0+k[0])*(m2+k[2]) + (m1+k[1])*(m3+k[3])
            *sum = sum
                .wrapping_add(u64::from(m0.wrapping_add(k0)) * u64::from(m2.wrapping_add(k2)))
                .wrapping_add(u64::from(m1.wrapping_add(k1)) * u64::from(m3.wrapping_add(k3)));
        }
    }

    // Final partial unit: zero-pad the tail bytes into a 16-byte scratch
    // and process it. Only allocated when `msg.len() % 16 != 0`.
    if tail_len != 0 {
        let mut tail = [0u8; NH_MESSAGE_UNIT];
        tail[..tail_len].copy_from_slice(&msg[full_units * NH_MESSAGE_UNIT..]);

        let m0 = le_u32_at(&tail, 0);
        let m1 = le_u32_at(&tail, 4);
        let m2 = le_u32_at(&tail, 8);
        let m3 = le_u32_at(&tail, 12);

        let key_ptr = full_units * NH_MESSAGE_UNIT;
        for (pass, sum) in sums.iter_mut().enumerate() {
            let k_base = key_ptr + pass * NH_MESSAGE_UNIT;
            let k0 = le_u32_at(key, k_base);
            let k1 = le_u32_at(key, k_base + 4);
            let k2 = le_u32_at(key, k_base + 8);
            let k3 = le_u32_at(key, k_base + 12);

            *sum = sum
                .wrapping_add(u64::from(m0.wrapping_add(k0)) * u64::from(m2.wrapping_add(k2)))
                .wrapping_add(u64::from(m1.wrapping_add(k1)) * u64::from(m3.wrapping_add(k3)));
        }

        // Scrub the 16-byte tail scratch — it held a copy of input bytes.
        tail.zeroize();
    }

    // Serialize four u64 lanes little-endian → 32 bytes.
    let mut out = [0u8; 32];
    for (idx, lane) in sums.iter().enumerate() {
        out[idx * 8..idx * 8 + 8].copy_from_slice(&lane.to_le_bytes());
    }
    out
}

// === Poly1305 evaluation primitive =======================================
//
// `poly1305_eval(R, blocks) -> [u8; 16]` evaluates the Poly1305
// polynomial with the given R key and an S of zero, mirroring kernel
// `poly1305_core_emit(..., nonce = NULL)`.
//
// `blocks` MUST be a multiple of 16 bytes — the caller is responsible
// for any padding the application protocol requires. We feed full
// 16-byte chunks via the universal-hash block API (kernel
// `poly1305_core_blocks(..., hibit = 1)`).
//
// The `poly1305` dependency is built with `features = ["zeroize"]` at
// the workspace level, so the returned `Poly1305` instance scrubs its
// internal state (`r`, `h`, `pad` limbs derived from the secret key)
// in `Drop`.

fn poly1305_with_zero_s(r: &[u8; POLY1305_R_SIZE]) -> poly1305::Poly1305 {
    use poly1305::Poly1305;
    use poly1305::universal_hash::KeyInit;

    // Pair R with a zero S half so finalize() does not add a secret.
    let mut key = [0u8; 32];
    key[..POLY1305_R_SIZE].copy_from_slice(r);
    let mac = Poly1305::new(&key.into());
    key.zeroize();
    mac
}

fn poly1305_eval(r: &[u8; POLY1305_R_SIZE], blocks: &[u8]) -> [u8; 16] {
    debug_assert!(
        blocks.len().is_multiple_of(16),
        "poly1305_eval requires 16-byte-aligned input"
    );

    let mac = poly1305_with_zero_s(r);
    // `blocks` must be 16-byte aligned (caller's responsibility). Each full
    // 16-byte chunk is processed with the 2^128 high bit set, matching
    // kernel `poly1305_core_blocks(..., hibit = 1)`.  For full-block-only
    // input, `compute_unpadded` and the block-update path are identical.
    let tag = mac.compute_unpadded(blocks);

    let mut out = [0u8; 16];
    out.copy_from_slice(tag.as_slice());
    out
}

// === NHPoly1305 combined hash ============================================
//
// MessageHash component of Adiantum's H. For each 1024-byte chunk of
// the message, compute NH(chunk) → 32 bytes and feed it directly into
// a running Poly1305 instance via `update_padded`. Since each NH output
// is exactly 32 bytes (2 full Poly1305 blocks), `update_padded` emits
// no extra padding — it behaves identically to kernel
// `poly1305_core_blocks(..., hibit=1)` for full-block input.
//
// Empty message → output 0 (per Adiantum design §4.5).

fn nhpoly1305(nh_key: &[u8; NH_KEY_SIZE], poly_r: &[u8; POLY1305_R_SIZE], msg: &[u8]) -> [u8; 16] {
    use poly1305::universal_hash::UniversalHash;

    if msg.is_empty() {
        return [0u8; 16];
    }

    let mut mac = poly1305_with_zero_s(poly_r);
    for chunk in msg.chunks(NH_CHUNK_BYTES) {
        // The 32-byte NH output is a hash of secret NH key material and
        // must not outlive its use. Scrub it before this binding leaves
        // scope. (`nh_chunk` already zeroizes its own scratch buffer;
        // this keeps the call-site consistent.)
        let mut nh = nh_chunk(nh_key, chunk);
        // NH output is 32 bytes = 2 full Poly1305 blocks. `update_padded`
        // on aligned input calls `update(blocks)` → `proc_block` per block
        // → `compute_block(block, false)` which sets hibit=1, matching
        // kernel `poly1305_core_blocks(..., hibit=1)`.
        mac.update_padded(&nh);
        nh.zeroize();
    }

    let tag = mac.finalize();
    let mut out = [0u8; 16];
    out.copy_from_slice(tag.as_slice());
    out
}

// === Stream IV derivation ================================================
//
// Build the 24-byte XChaCha12 nonce from C_M: nonce = C_M || 1u64_le.

fn stream_iv(c_m: &[u8; 16]) -> [u8; 24] {
    let mut nonce = [0u8; 24];
    nonce[..16].copy_from_slice(c_m);
    nonce[16..24].copy_from_slice(&1u64.to_le_bytes());
    nonce
}

// === AES-256 single block ================================================
//
// One-shot single-block AES-256 decrypt for the inner block cipher step.
// The encrypt counterpart is only used by the round-trip test below, so it
// is `#[cfg(test)]`-gated to avoid a dead-code warning once consumers wire
// the module in and `#![allow(dead_code)]` is lifted.

#[cfg(test)]
fn aes256_encrypt_block(key: &[u8; AES_KEY_SIZE], block: &[u8; 16]) -> [u8; 16] {
    use aes::Aes256;
    use aes::cipher::generic_array::GenericArray;
    use aes::cipher::{BlockEncrypt, KeyInit};

    let cipher = Aes256::new(GenericArray::from_slice(key));
    let mut buf = *block;
    cipher.encrypt_block(GenericArray::from_mut_slice(&mut buf));
    buf
}

fn aes256_decrypt_block(key: &[u8; AES_KEY_SIZE], block: &[u8; 16]) -> [u8; 16] {
    use aes::Aes256;
    use aes::cipher::generic_array::GenericArray;
    use aes::cipher::{BlockDecrypt, KeyInit};

    let cipher = Aes256::new(GenericArray::from_slice(key));
    let mut buf = *block;
    cipher.decrypt_block(GenericArray::from_mut_slice(&mut buf));
    buf
}

// === Full hash H_K(T, M_L) ===============================================
//
// HeaderHash + MessageHash, mod 2^128 (little-endian). Returns 16 bytes.
//
// HeaderHash: Poly1305-eval over a 48-byte block composed of:
//   [m_l_bits_le(8) || zeros(8) || tweak[0..16](16) || tweak[16..32](16)]
//
// MessageHash: NHPoly1305 over M_L.
//
// Per Adiantum paper §4.5 and kernel adiantum.c `adiantum_hash`.

fn hash_h(
    header_poly: &[u8; POLY1305_R_SIZE],
    msg_poly: &[u8; POLY1305_R_SIZE],
    nh_key: &[u8; NH_KEY_SIZE],
    tweak: &[u8; ADIANTUM_TWEAK_SIZE],
    m_l_bits: u64,
    m_l: &[u8],
) -> [u8; 16] {
    // HeaderHash: 3 × 16-byte Poly1305 blocks.
    let mut header = [0u8; 48];
    header[..8].copy_from_slice(&m_l_bits.to_le_bytes());
    // header[8..16] stays zero (8-byte zero pad in block_0).
    header[16..32].copy_from_slice(&tweak[..16]);
    header[32..48].copy_from_slice(&tweak[16..]);
    let header_tag = poly1305_eval(header_poly, &header);

    let msg_tag = nhpoly1305(nh_key, msg_poly, m_l);

    // (header_tag + msg_tag) mod 2^128, little-endian.
    let h = u128::from_le_bytes(header_tag).wrapping_add(u128::from_le_bytes(msg_tag));
    h.to_le_bytes()
}

